# --- Roo/Zoo custom modes (shared by the generic .agents and native roo targets) -
# VS Code tool id -> Roo Code tool group. Roo groups are coarse: read, edit, browser,
# command, mcp. "search" folds into read; "todo"/"agent"/"vscode" have no group.
map_tool_group() {
  case "$1" in
    read|search) echo "read" ;;
    edit)        echo "edit" ;;
    execute)     echo "command" ;;
    web|fetch)   echo "browser" ;;
    *)           echo "" ;;
  esac
}

roo_groups_line() { # roo_groups_line <file>
  local id mapped g seen=" " joined=""
  for id in $(tool_ids "$1"); do
    mapped="$(map_tool_group "$id")"
    [[ -n "$mapped" ]] || continue
    case "$seen" in *" $mapped "*) continue ;; esac
    seen="$seen$mapped "
  done
  for g in read edit browser command mcp; do
    case "$seen" in *" $g "*) joined="$joined, $g" ;; esac
  done
  [[ -n "$joined" ]] || joined=", read"
  echo "groups: [${joined#, }]"
}

# requirements-analyst -> "Requirements Analyst"   (awk: portable across GNU and BSD)
title_case() {
  echo "$1" | awk '{ gsub(/-/," "); for(i=1;i<=NF;i++) $i=toupper(substr($i,1,1)) substr($i,2); print }'
}

# roo_mode <file> <key_indent> — one custom-mode mapping. Block scalars carry an explicit
# indentation indicator (|2- / |4-), so a body whose first line is indented (a code
# block, a nested list) still parses: YAML would otherwise infer the indent from it.
roo_mode() {
  local src="$1" ki="$2" base slug name desc role pad
  base="$(basename "$src" .agent.md)"
  slug="$(field_value "$src" name)"; [[ -n "$slug" ]] || slug="$base"
  name="$(title_case "$slug")"
  desc="$(field_value "$src" description)"
  role="$(persona_of "$src")"
  [[ -n "$role" ]] || role="$desc"             # fallback if no "You are" line
  pad="$(printf '%*s' "$ki" '')"
  echo "slug: $slug"
  echo "${pad}name: $name"
  echo "${pad}roleDefinition: |2-"
  printf '%s\n' "$role" | indent_block $((ki + 2))
  if [[ -n "$desc" ]]; then
    echo "${pad}whenToUse: |2-"
    printf '%s\n' "$desc" | indent_block $((ki + 2))
  fi
  echo "${pad}$(roo_groups_line "$src")"
  echo "${pad}customInstructions: |2-"
  body_of "$src" | indent_block $((ki + 2))
}

# Generic ".agents" target: one YAML file per agent, each a single Roo-style custom-mode
